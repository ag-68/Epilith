def test_asml_table_sums_latest_four_sales_quarters():
    amounts = parse_statement_text(ASML_QUARTERS, "EUR", source_id="report")
    total, source, start, end = sum_independent_quarters(amounts, "revenue", set())
    assert source == "report"
    assert end == date(2026, 6, 28)
    assert start == date(2025, 6, 30)
    assert total == Decimal("35327500000")
    cash = [item for item in amounts if item.metric == "cash"][-1]
    assert cash.value == Decimal("6671900000")
    debt = [item for item in amounts if item.metric == "total_debt"][-1]
    assert debt.value == Decimal("1984400000")
    capex = [item for item in amounts if item.metric == "capex" and item.end == date(2026, 6, 28)]
    assert capex[0].value == Decimal("299400000")


def test_column_table_keeps_home_currency_and_parent_profit():
    amounts = parse_statement_text(TSMC_COLUMNS, "TWD", source_id="pdf")
    revenue = [item for item in amounts if item.metric == "revenue" and item.kind == "quarter"]
    by_end = {item.end: item.value for item in revenue}
    assert by_end[date(2026, 6, 30)] == Decimal("1270381000000")
    assert by_end[date(2026, 3, 31)] == Decimal("1134103000000")
    profit = [item for item in amounts if item.metric == "net_income" and item.end == date(2026, 6, 30)]
    assert max(profit, key=lambda item: item.priority).value == Decimal("706562000000")
    cash = [item for item in amounts if item.metric == "cash" and item.end == date(2026, 6, 30)][0]
    assert cash.value == Decimal("3134218000000")
    capex = [
        item for item in amounts if item.metric == "capex" and item.kind == "quarter" and item.end == date(2026, 6, 30)
    ][0]
    assert capex.value == Decimal("496002000000")


def test_newer_quarter_is_not_mixed_into_an_older_window():
    amounts = parse_statement_text(ASML_QUARTERS, "EUR", source_id="report")
    from data.statement_table import StatedAmount

    later = StatedAmount(
        "revenue",
        "quarter",
        date(2026, 6, 29),
        date(2026, 9, 27),
        Decimal("1000000000"),
        "later",
        1,
    )
    total, _source, _start, end = sum_independent_quarters(
        [*amounts, later],
        "revenue",
        set(),
        end_on=date(2026, 6, 28),
    )
    assert end == date(2026, 6, 28)
    assert total == Decimal("35327500000")


def test_same_document_cannot_cross_check_itself():
    amounts = parse_statement_text(ASML_QUARTERS, "EUR", source_id="report")
    assert sum_independent_quarters(amounts, "revenue", {"report"}) is None


def test_half_year_plus_later_quarters_rebuilds_the_same_year():
    from data.statement_table import StatedAmount, stated_year_total

    amounts = [
        StatedAmount("revenue", "ytd", date(2025, 1, 1), date(2025, 6, 29), Decimal("15433200000"), "report", 1),
        StatedAmount("revenue", "quarter", date(2025, 6, 30), date(2025, 9, 28), Decimal("7516000000"), "report", 1),
        StatedAmount("revenue", "quarter", date(2025, 9, 29), date(2025, 12, 31), Decimal("9718100000"), "report", 1),
    ]
    total, source = stated_year_total(amounts, "revenue", date(2025, 1, 1), date(2025, 12, 31))
    assert source == "report"
    assert total == Decimal("32667300000")


def test_year_to_date_rebuilds_twelve_months_from_another_document():
    from data.statement_table import StatedAmount, ttm_candidates_from_annual_and_ytd

    amounts = [
        StatedAmount("revenue", "ytd", date(2026, 1, 27), date(2026, 7, 26), Decimal("177837000000"), "other", 1),
        StatedAmount("revenue", "ytd", date(2025, 1, 28), date(2025, 7, 27), Decimal("90805000000"), "other", 1),
        StatedAmount("revenue", "annual", date(2025, 1, 26), date(2026, 1, 25), Decimal("215938000000"), "year", 1),
    ]
    found = ttm_candidates_from_annual_and_ytd(amounts, "revenue", {"quarter"}, date(2026, 7, 26))
    assert found == [(Decimal("302970000000"), "year")]


def test_year_to_date_from_the_same_statement_does_not_confirm_the_total():
    from data.statement_table import StatedAmount, ttm_candidates_from_annual_and_ytd

    amounts = [
        StatedAmount("revenue", "ytd", date(2026, 1, 27), date(2026, 7, 26), Decimal("177837000000"), "quarter", 1),
        StatedAmount("revenue", "ytd", date(2025, 1, 28), date(2025, 7, 27), Decimal("90805000000"), "quarter", 1),
        StatedAmount("revenue", "annual", date(2025, 1, 26), date(2026, 1, 25), Decimal("215938000000"), "year", 1),
    ]
    found = ttm_candidates_from_annual_and_ytd(amounts, "revenue", {"quarter"}, date(2026, 7, 26))
    assert found == []


def test_html_release_keeps_the_quarter_and_the_six_month_total():
    from data.html_tables import html_tables_to_text

    html = """
    <table>
      <tr><td></td><td colspan="5">Three Months Ended</td><td colspan="5">Six Months Ended</td></tr>
      <tr>
        <td></td>
        <td colspan="2">July 26,</td><td></td><td colspan="2">July 27,</td>
        <td colspan="2">July 26,</td><td></td><td colspan="2">July 27,</td>
      </tr>
      <tr>
        <td></td>
        <td colspan="2">2026</td><td></td><td colspan="2">2025</td>
        <td colspan="2">2026</td><td></td><td colspan="2">2025</td>
      </tr>
      <tr>
        <td>Revenue</td>
        <td>$</td><td>96,221</td><td></td><td>$</td><td>46,743</td>
        <td>$</td><td>177,837</td><td></td><td>$</td><td>90,805</td>
      </tr>
    </table>
    """
    amounts = parse_statement_text(html_tables_to_text(html) + "\nin millions", "USD", "page")
    quarter = [item for item in amounts if item.metric == "revenue" and item.kind == "quarter"]
    ytd = [item for item in amounts if item.metric == "revenue" and item.kind == "ytd"]
    assert {item.end: item.value for item in quarter}[date(2026, 7, 26)] == Decimal("96221000000")
    assert {item.end: item.value for item in ytd}[date(2026, 7, 26)] == Decimal("177837000000")
